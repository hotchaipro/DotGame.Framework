using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;

namespace DotGame.Analyzers;

/// <summary>
/// Suppresses banned-API errors (RS0030) in generated code, so the ban applies to the code that's
/// written: System.Text.Json's source generator, for one, uses reflection for its metadata and in
/// its exception messages, and nothing about that is ours to change.
/// </summary>
/// <remarks>
/// A suppressor is the only way: the compiler applies per-file severities (.editorconfig) only to
/// the files it's given, never to a source generator's output.
/// </remarks>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class GeneratedCodeBannedApiSuppressor : DiagnosticSuppressor
{
    private static readonly SuppressionDescriptor GeneratedCode = new SuppressionDescriptor(
        id: "DG0001",
        suppressedDiagnosticId: "RS0030",
        justification: "Generated code may use banned APIs; the ban is for written code.");

    public override ImmutableArray<SuppressionDescriptor> SupportedSuppressions => ImmutableArray.Create(GeneratedCode);

    public override void ReportSuppressions(
        SuppressionAnalysisContext context)
    {
        foreach (var diagnostic in context.ReportedDiagnostics)
        {
            var tree = diagnostic.Location.SourceTree;
            if ((tree is not null) && IsGenerated(tree, context))
            {
                context.ReportSuppression(Suppression.Create(GeneratedCode, diagnostic));
            }
        }
    }

    // Generated files start with an <auto-generated> comment, as source generators' output does
    private static bool IsGenerated(
        SyntaxTree tree,
        SuppressionAnalysisContext context)
    {
        foreach (var trivia in tree.GetRoot(context.CancellationToken).GetLeadingTrivia())
        {
            if (trivia.ToString().Contains("<auto-generated"))
            {
                return true;
            }
        }

        return false;
    }
}
