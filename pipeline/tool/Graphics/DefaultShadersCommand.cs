using System.Text;
using System.Text.RegularExpressions;

namespace DotGame.Framework.ContentPipeline.BuildTool.Graphics;

/// <summary>
/// Compiles the default sprite shader and wraps the result in a generated C#
/// source file (DefaultShaderSource.g.cs) as compile-time constants:
/// <code>
///   spirv (desktop)        SPIR-V and DXIL as ReadOnlySpan&lt;byte&gt; properties, MSL as const strings
///   msl   (iOS)            MSL as const strings
///   glsl  (WebGL, Android) GLSL ES 300 as const strings
/// </code>
/// </summary>
internal static class DefaultShadersCommand
{
    public const string Name = "default-shaders";
    public const string ErrorCode = "SHD0002";

    public static void Run(CommandLineOptions options)
    {
        var compiler = new ShaderCompiler
        {
            SlangC = options.GetToolPath("slangc", "slangc"),
            SpirvCross = options.GetToolPath("spirv-cross", "spirv-cross"),
            Spirv2Dxil = options.GetToolPath("spirv2dxil", "spirv2dxil"),
        };
        string inputFile = options.GetPath("input");
        string outputDir = options.GetPath("output-dir");
        string target = options.GetChoice("target", null, "spirv", "msl", "glsl");
        string @namespace = options.GetRequired("namespace");
        options.ThrowIfUnrecognized();

        // Compiled into a scratch directory that is deleted afterwards, so the
        // output directory only holds the generated source.
        string baseName = Path.GetFileNameWithoutExtension(inputFile);
        string shaderDir = Path.Combine(outputDir, "Shaders");
        if (Directory.Exists(shaderDir))
        {
            Directory.Delete(shaderDir, recursive: true);
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine($"namespace {@namespace};");
        source.AppendLine();
        source.AppendLine("internal static class DefaultShaderSource");
        source.AppendLine("{");
        string Shader(string extension) => Path.Combine(shaderDir, baseName + extension);
        switch (target)
        {
            case "spirv":
                compiler.Compile(inputFile, shaderDir, baseName, shaderDir, ShaderTypes.SpirV | ShaderTypes.Msl | ShaderTypes.Dxil);
                source.AppendLine("    // SPIR-V (Vulkan)");
                source.AppendLine($"    internal static System.ReadOnlySpan<byte> VertexShaderSpirV => [{ToCollectionExpression(Shader(".vert.spv"))}];");
                source.AppendLine($"    internal static System.ReadOnlySpan<byte> FragmentShaderSpirV => [{ToCollectionExpression(Shader(".frag.spv"))}];");
                source.AppendLine();
                AppendMsl(source, Shader(".vert.msl"), Shader(".frag.msl"));
                source.AppendLine();
                source.AppendLine("    // DXIL (D3D12)");
                source.AppendLine($"    internal static System.ReadOnlySpan<byte> VertexShaderDXIL => [{ToCollectionExpression(Shader(".vert.dxil"))}];");
                source.AppendLine($"    internal static System.ReadOnlySpan<byte> FragmentShaderDXIL => [{ToCollectionExpression(Shader(".frag.dxil"))}];");
                break;

            case "msl":
                compiler.Compile(inputFile, shaderDir, baseName, shaderDir, ShaderTypes.Msl);
                AppendMsl(source, Shader(".vert.msl"), Shader(".frag.msl"));
                break;

            case "glsl":
                compiler.Compile(inputFile, shaderDir, baseName, shaderDir, ShaderTypes.Glsl);
                string combined = File.ReadAllText(Shader(".glsl"));
                source.AppendLine($"    internal const string VertexShader = \"{ToStringLiteral(ExtractGlslSection(combined, "VERTEX"))}\";");
                source.AppendLine($"    internal const string FragmentShader = \"{ToStringLiteral(ExtractGlslSection(combined, "FRAGMENT"))}\";");
                break;
        }
        source.AppendLine("}");

        File.WriteAllText(Path.Combine(outputDir, "DefaultShaderSource.g.cs"), source.ToString());
        Directory.Delete(shaderDir, recursive: true);
    }

    private static void AppendMsl(StringBuilder source, string vertexMsl, string fragmentMsl)
    {
        source.AppendLine("    // MSL (Metal)");
        source.AppendLine($"    internal const string VertexShaderMSL = \"{ToStringLiteral(File.ReadAllText(vertexMsl))}\";");
        source.AppendLine($"    internal const string FragmentShaderMSL = \"{ToStringLiteral(File.ReadAllText(fragmentMsl))}\";");
    }

    private static string ExtractGlslSection(string combined, string stage)
    {
        var match = Regex.Match(combined, $@"#ifdef {stage}\n(.*?)\n#endif", RegexOptions.Singleline | RegexOptions.CultureInvariant);
        if (!match.Success)
        {
            throw new ContentBuildException($"Could not extract the {stage} section from the combined GLSL.");
        }
        return match.Groups[1].Value.Trim();
    }

    private static string ToCollectionExpression(string path)
    {
        byte[] bytes = File.ReadAllBytes(path);
        var builder = new StringBuilder(bytes.Length * 6);
        foreach (byte b in bytes)
        {
            if (builder.Length > 0)
            {
                builder.Append(", ");
            }
            builder.Append("0x").Append(b.ToString("X2", System.Globalization.CultureInfo.InvariantCulture));
        }
        return builder.ToString();
    }

    private static string ToStringLiteral(string text) => text
        .Replace("\\", "\\\\", StringComparison.Ordinal)
        .Replace("\"", "\\\"", StringComparison.Ordinal)
        .Replace("\r\n", "\\n", StringComparison.Ordinal)
        .Replace("\n", "\\n", StringComparison.Ordinal);
}
